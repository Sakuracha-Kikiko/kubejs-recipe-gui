package com.sakuracha.kubejsrecipegui.server;

import com.sakuracha.kubejsrecipegui.spec.DeleteMode;
import com.sakuracha.kubejsrecipegui.spec.WriteMode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;

/**
 * 维护 {@code kubejs/server_scripts/generated_recipes.js} 里由本模组生成的那一段。
 * 合并逻辑是纯字符串处理，可以脱离游戏单独测试。
 */
public final class ScriptStore {
    public static final String RELATIVE_PATH = "kubejs/server_scripts/generated_recipes.js";
    public static final String MARK_BEGIN = "// <kubejs-recipe-gui:begin>";
    public static final String MARK_END = "// <kubejs-recipe-gui:end>";
    /** 脚本文件的总大小上限。 */
    public static final int MAX_FILE_BYTES = 1024 * 1024;

    private static final String HEADER = String.join("\n",
            "// 由 kubejs-recipe-gui 生成。标记块内的内容会在每次写入时被重新生成。",
            "// Generated by kubejs-recipe-gui. Everything between the markers is regenerated.",
            "");

    private ScriptStore() {
    }

    /** 待写入的一条配方：脚本文本加上用于条件删除的元数据。 */
    public record Entry(String id, String station, String output, String inputs, String text) {
    }

    public enum Outcome {
        CREATED, REPLACED, SKIPPED
    }

    public record MergeResult(String content, Outcome outcome, List<String> removed) {
    }

    public static String skeleton(String entries) {
        return HEADER
                + "ServerEvents.recipes(event => {\n"
                + MARK_BEGIN + "\n"
                + entries
                + MARK_END + "\n"
                + "})\n";
    }

    /**
     * 把一条配方合并进已有的脚本内容。
     *
     * @param existing 现有文件内容，{@code null} 或空串表示文件还不存在
     */
    public static MergeResult merge(String existing, Entry entry, WriteMode mode,
                                    DeleteMode deleteMode, String deleteValue) {
        if (existing == null || existing.isBlank()) {
            return new MergeResult(skeleton(entry.text()), Outcome.CREATED, List.of());
        }

        int begin = existing.indexOf(MARK_BEGIN);
        int end = existing.indexOf(MARK_END);
        if (begin < 0 || end < begin) {
            String appended = existing.endsWith("\n") ? existing : existing + "\n";
            appended += "ServerEvents.recipes(event => {\n"
                    + MARK_BEGIN + "\n"
                    + entry.text()
                    + MARK_END + "\n"
                    + "})\n";
            return new MergeResult(appended, Outcome.CREATED, List.of());
        }

        String before = existing.substring(0, begin + MARK_BEGIN.length()) + "\n";
        String after = existing.substring(end);
        List<Entry> entries = parse(existing.substring(begin + MARK_BEGIN.length(), end));

        List<String> removed = new ArrayList<>();
        List<Entry> kept = new ArrayList<>();
        for (Entry old : entries) {
            if (matchesDelete(old, entry, deleteMode, deleteValue)) {
                removed.add(old.id());
            } else {
                kept.add(old);
            }
        }

        boolean sameId = false;
        for (Entry old : kept) {
            if (old.id().equals(entry.id())) {
                sameId = true;
                break;
            }
        }
        if (sameId && mode == WriteMode.SKIP) {
            return new MergeResult(existing, Outcome.SKIPPED, removed);
        }

        List<Entry> result = new ArrayList<>();
        boolean replaced = false;
        for (Entry old : kept) {
            if (old.id().equals(entry.id())) {
                if (!replaced) {
                    result.add(entry);
                    replaced = true;
                }
            } else {
                result.add(old);
            }
        }
        if (!replaced) {
            result.add(entry);
        }

        StringBuilder content = new StringBuilder(before);
        for (Entry e : result) {
            content.append(e.text());
        }
        content.append(after);

        Outcome outcome = replaced || !removed.isEmpty() ? Outcome.REPLACED : Outcome.CREATED;
        if (content.toString().equals(existing)) {
            return new MergeResult(existing, Outcome.SKIPPED, removed);
        }
        return new MergeResult(content.toString(), outcome, removed);
    }

    private static boolean matchesDelete(Entry old, Entry current, DeleteMode mode, String value) {
        if (mode == null || mode == DeleteMode.NONE) {
            return false;
        }
        return switch (mode) {
            case SAME_TYPE -> old.station().equals(current.station());
            case BY_OUTPUT -> itemPart(old.output()).equals(value.trim());
            case BY_TAG -> old.inputs().contains("#" + (value.trim().startsWith("#") ? value.trim().substring(1) : value.trim()));
            case BY_ID -> old.id().equals(value.trim());
            default -> false;
        };
    }

    private static String itemPart(String output) {
        int space = output.lastIndexOf(" x");
        return space > 0 ? output.substring(0, space) : output;
    }

    /** 解析标记块里的条目；没有 {@code // id: } 开头的文本会被忽略。 */
    public static List<Entry> parse(String block) {
        List<Entry> entries = new ArrayList<>();
        String id = null;
        String station = "";
        String output = "";
        String inputs = "";
        StringBuilder text = new StringBuilder();
        for (String line : block.split("\n", -1)) {
            if (line.startsWith("// id: ")) {
                if (id != null) {
                    entries.add(new Entry(id, station, output, inputs, text.toString()));
                }
                id = line.substring("// id: ".length()).trim();
                station = "";
                output = "";
                inputs = "";
                text.setLength(0);
                text.append(line).append('\n');
            } else if (id != null) {
                if (line.startsWith("// station: ")) {
                    station = line.substring("// station: ".length()).trim();
                } else if (line.startsWith("// output: ")) {
                    output = line.substring("// output: ".length()).trim();
                } else if (line.startsWith("// inputs: ")) {
                    inputs = line.substring("// inputs: ".length()).trim();
                }
                text.append(line).append('\n');
            }
        }
        if (id != null) {
            entries.add(new Entry(id, station, output, inputs, text.toString()));
        }
        return entries;
    }

    public static void write(Path file, String content) throws IOException {
        if (content.getBytes(StandardCharsets.UTF_8).length > MAX_FILE_BYTES) {
            throw new IOException("Script file too large");
        }
        Path parent = file.getParent();
        if (parent != null) {
            Files.createDirectories(parent);
        }
        Path temp = file.resolveSibling(file.getFileName() + ".tmp");
        Files.writeString(temp, content, StandardCharsets.UTF_8);
        try {
            Files.move(temp, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException e) {
            Files.move(temp, file, StandardCopyOption.REPLACE_EXISTING);
        }
    }
}
